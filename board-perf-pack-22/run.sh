#!/usr/bin/env bash
# run.sh -- K3 board performance runner for the a100c operator pack.
#
# Pins every execution to the A100 AI cores (CPU 8-15; 0-7 are the system
# cores) and measures each case at --threads 1 and --threads 8:
#   warmup (1 execution, runtime self-check) then a timed --repeats loop.
# Per-iteration time = (whole timed loop) / repeats and therefore includes the
# runtime's per-repeat input snapshot restore + output compare pass (see
# README.md); process startup is amortized over the loop.
#
# Environment overrides:
#   A100_CPUS=8-15        CPU list to pin (default 8-15 = the A100 cores)
#   A100_THREADS="1 8"    thread counts to measure (default: 1 and 8)
#   A100_REPEATS_MULT=1   multiply every case's repeat count
set -u
cd "$(dirname "$0")"

CPUS="${A100_CPUS:-8-15}"
THREADS_LIST="${A100_THREADS:-1 8}"
REPEATS_MULT="${A100_REPEATS_MULT:-1}"
RESULTS="results"
mkdir -p "$RESULTS"
STAMP="$(date +%Y%m%d-%H%M%S)"
SUMMARY="$RESULTS/summary-$STAMP.tsv"
RAW="$RESULTS/raw-$STAMP.log"

# ---------------------------------------------------------------- checks ---
if [ "$(uname -m)" != "riscv64" ]; then
  echo "warning: uname -m is $(uname -m), expected riscv64 -- running anyway" >&2
fi
command -v taskset >/dev/null 2>&1 || {
  echo "ERROR: taskset not found (need util-linux or busybox)" >&2; exit 1; }

# The board's default cgroup (allow_cpu) usually confines the shell to 0-7.
# The A100 cores are 8-15: widen our own cgroup's cpuset if needed, and pin
# every launch with taskset regardless.
if ! taskset -c "$CPUS" true 2>/dev/null; then
  allowed="$(awk '/Cpus_allowed_list/ {print $2}' /proc/self/status)"
  echo "ERROR: cannot pin to CPUs $CPUS (currently allowed: $allowed)" >&2
  cg="/sys/fs/cgroup$(awk -F: 'NR==1{print $3}' /proc/self/cgroup)"
  if [ -w "$cg/cpuset.cpus" ]; then
    if echo "$CPUS" > "$cg/cpuset.cpus" 2>/dev/null; then
      echo "  widened $cg/cpuset.cpus -> $CPUS" >&2
    else
      echo "  failed to write $cg/cpuset.cpus (not root?); set allow_cpu=8-15 manually and re-run" >&2; exit 1
    fi
  else
    echo "  set allow_cpu / cpuset to include $CPUS (e.g. as root: echo $CPUS > $cg/cpuset.cpus) and re-run" >&2
    exit 1
  fi
fi

now_us() {
  if [ -n "${EPOCHREALTIME:-}" ]; then       # bash >= 5, microsecond precision
    echo "${EPOCHREALTIME/./}"               # sec.usec -> usec since epoch
  else
    date +%s%N
  fi
}

# name:repeats lines; generated by stage_pack.py (smoke-passing cases only)
[ -f cases.conf ] || { echo "ERROR: cases.conf missing" >&2; exit 1; }

printf 'case\tthreads\tus_per_iter\tpool_init\tmin_worker_items\n' | tee "$SUMMARY"

run_config() {  # $1 name  $2 threads  $3 repeats -> prints one summary row
  local name="$1" threads="$2" reps="$3"
  local exe="bin/$name/operator_exec" bundle="cases/$name/bundle.bin"
  local out t0 t1 us line
  [ -x "$exe" ] || { echo "SKIP $name t$threads: no executable" >&2; return 1; }

  # warmup + runtime self-check (repeat-consistency, pool init count)
  out="$(timeout 600 taskset -c "$CPUS" "$exe" --bundle "$bundle" --threads "$threads" --repeats 1)" || {
    echo "FAIL $name t$threads: warmup exit $?" >&2; echo "$out" >> "$RAW"; return 1; }
  echo "[$name t$threads warmup] $out" >> "$RAW"
  case "$out" in *'"status":"ok"'*) ;; *)
    echo "FAIL $name t$threads: runtime status not ok: $out" >&2; return 1 ;; esac

  reps=$(( reps * REPEATS_MULT ))
  t0="$(now_us)"
  out="$(timeout 600 taskset -c "$CPUS" "$exe" --bundle "$bundle" --threads "$threads" --repeats "$reps")" || {
    echo "FAIL $name t$threads: timed exit $?" >&2; return 1; }
  t1="$(now_us)"
  echo "[$name t$threads timed x$reps] $out" >> "$RAW"
  case "$out" in *'"status":"ok"'*) ;; *)
    echo "FAIL $name t$threads: runtime status not ok: $out" >&2; return 1 ;; esac

  us=$(( (t1 - t0) / reps ))
  local pool_init items
  pool_init="$(echo "$out" | grep -o '"pool_initializations":[0-9]*' | cut -d: -f2)"
  items="$(echo "$out" | grep -o '"items":[0-9]*' | cut -d: -f2 | sort -n | head -1)"
  printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$threads" "$us" "${pool_init:-?}" "${items:-?}" | tee -a "$SUMMARY"
}

# ------------------------------------------------------------------- run ---
while IFS= read -r line; do
  case "$line" in ''|'#'*) continue ;; esac
  name="${line%%:*}"; reps="${line##*:}"
  for t in $THREADS_LIST; do
    run_config "$name" "$t" "$reps"
  done
done < cases.conf

# --------------------------------------------------------------- speedup ---
echo
echo "speedup (t1/t8, same case):"
awk -F'\t' 'NR>1 { v[$1"|"$2]=$3 }
  END { for (k in v) { split(k,p,"|"); if (p[2]=="1") one[p[1]]=v[k] }
        for (k in v) { split(k,p,"|"); if (p[2]=="8" && (p[1] in one))
          printf "  %-18s %8.2fx\n", p[1], one[p[1]]/v[k] } }' "$SUMMARY"
echo
echo "summary -> $SUMMARY"
echo "raw runtime JSON -> $RAW"
